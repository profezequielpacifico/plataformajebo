export function rutaDe(page) {
    return resolverRuta(page, ROUTE_PERMISSIONS).ruta;
}

export function canAccess(user, page) {
    if (PUBLIC_ROUTES.includes(page)) return true;
    const roleId = getRoleId(user);
    if (roleId === null) return false;
    const ruta = rutaDe(page);
    if (!ruta) return false;
    return ROUTE_PERMISSIONS[ruta].includes(roleId);
}
